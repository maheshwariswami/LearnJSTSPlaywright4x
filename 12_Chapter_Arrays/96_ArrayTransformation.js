//Map Filters

//if everyone true answer is true
console.log([80,90,100].every(s=> s>70)) //true

console.log([80,60,100].every(s=> s>70)) //false

// some elemnets must satisfy condition // at least one shd true
console.log([10,20,30,40,50].some(no => no >30)) //true
console.log([10,20,30].some(no=> no>40)) // falsee
